// setup.mjs — `heimdall setup`: hardware-aware config generation + daemon install.
//
// Detects the machine (accelerator, cores), renders an annotated
// ~/.graft/config.yaml for the graft C++ daemon, optionally downloads an
// embedding model, and installs/repairs the launchd daemon. Pure helpers
// (detectHardware, renderConfig, parseSetupArgs) are exported for tests;
// runSetup() is the CLI entry.
import { execFileSync } from "node:child_process";
import {
  existsSync, mkdirSync, readFileSync, writeFileSync, copyFileSync, statSync, renameSync, chmodSync, unlinkSync,
} from "node:fs";
import { dirname, join } from "node:path";
import os from "node:os";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url)); // bin/lib
const ROOT = dirname(dirname(HERE)); // repo root
export const CATALOG = JSON.parse(readFileSync(join(HERE, "models-catalog.json"), "utf8"));

export const graftConfigPath = () => join(os.homedir(), ".graft", "config.yaml");
export const modelsDir = () => join(os.homedir(), ".graft", "models");
export const plistPath = () => join(os.homedir(), "Library", "LaunchAgents", "com.graft.daemon.plist");
export const localBinGraftd = () => join(os.homedir(), ".local", "bin", "graftd");

const sh = (cmd, args) => {
  try {
    return { ok: true, out: execFileSync(cmd, args, { encoding: "utf8" }).trim() };
  } catch (e) {
    return { ok: false, out: String(e.stdout || ""), err: String(e.stderr || e.message || "") };
  }
};

// ---------------------------------------------------------------------------
// Hardware detection
// ---------------------------------------------------------------------------
export function detectHardware() {
  const platform = process.platform;
  let cores = os.cpus().length;
  let arm = false;
  let accel = "cpu";

  if (platform === "darwin") {
    const pc = sh("sysctl", ["-n", "hw.physicalcpu"]);
    if (pc.ok) cores = parseInt(pc.out, 10) || cores;
    const a = sh("sysctl", ["-n", "hw.optional.arm64"]);
    arm = a.ok && a.out.trim() === "1";
    if (arm) accel = "metal"; // Apple Silicon → llama.cpp Metal backend
  } else if (platform === "linux") {
    const n = sh("nproc", []);
    if (n.ok) cores = parseInt(n.out.trim().split("\n")[0], 10) || cores;
    if (sh("nvidia-smi", ["-L"]).ok) accel = "cuda";
  }

  return { platform, cores, arm, accel, instances: cores >= 8 ? 2 : 1 };
}

// ---------------------------------------------------------------------------
// Config rendering — annotated YAML mirroring vendor/graft config.example.yaml
// ---------------------------------------------------------------------------
export function renderConfig(hw, c) {
  return `# ~/.graft/config.yaml — generated by \`heimdall setup\` on ${new Date().toISOString()}
# Hardware profile: ${hw.platform}, ${hw.cores} cores, accel=${hw.accel}
# Re-run \`heimdall setup\` to regenerate; prior config preserved as .bak-<timestamp>.
daemon:
  # [security] AF_UNIX socket — mode 0600; prefer XDG_RUNTIME_DIR on multi-user hosts.
  socket_path: "${c.socket_path}"
  # [security] SQLite store: everything (nodes, embeddings, edges). Treat as secret.
  db_path: "${c.db_path}"

embedding:
  # Path to the GGUF embedding model. Swapping models REQUIRES re-embedding:
  # existing vectors are not comparable across models. \`heimdall setup --model <id>\`
  # downloads to ~/.graft/models/ and rewrites this path.
  model_path: "${c.model_path}"
  # [perf] CPU threads for the llama backend. Sweet spot: physical cores.
  threads: ${c.threads}
  # [perf][quality] Max tokens per embed call. Lower = less RAM, hurts recall on long notes.
  ctx_size: ${c.ctx_size}
  # [perf] Independent llama contexts; each costs ~ctx memory + a decode slot.
  instances: ${c.instances}
  # [perf] GPU offload. true = Metal (Apple Silicon) or CUDA (NVIDIA build),
  # false = pure CPU. Must match the llama.cpp build backend.
  hardware_accel: ${c.hardware_accel}

verification:
  cross_encoder_enabled: ${c.cross_encoder_enabled}
  nli_enabled: ${c.nli_enabled}
  lex_strong_min_vec: ${c.lex_strong_min_vec}
  sem_strong_min_vec: ${c.sem_strong_min_vec}
  sem_strong_lex_margin: ${c.sem_strong_lex_margin}
  use_fused_gate: ${c.use_fused_gate}
  strong_min_fused: ${c.strong_min_fused}
  weak_min_fused: ${c.weak_min_fused}

cache:
  strong_hit_min_ce: ${c.strong_hit_min_ce}
  strong_hit_min_lex: ${c.strong_hit_min_lex}
  weak_hit_min_vec: ${c.weak_hit_min_vec}
  min_lex_overlap: ${c.min_lex_overlap}

retrieval:
  top_k: ${c.top_k}
  rrf_k_const: ${c.rrf_k_const}
  query_fallback_top_k: ${c.query_fallback_top_k}

rerank:
  enabled: ${c.rerank_enabled}
`;
}

// Default choices given a hardware profile + model path.
export function defaultChoices(hw, modelPath) {
  return {
    socket_path: "/tmp/graft-default.sock",
    db_path: join(os.homedir(), ".graft", "profiles", "default", "graft.db"),
    model_path: modelPath,
    threads: hw.cores,
    ctx_size: 8192,
    instances: hw.instances,
    hardware_accel: hw.accel === "metal" || hw.accel === "cuda",
    cross_encoder_enabled: false,
    nli_enabled: false,
    lex_strong_min_vec: 0.7,
    sem_strong_min_vec: 0.75,
    sem_strong_lex_margin: 0.015,
    use_fused_gate: true,
    strong_min_fused: 0.62,
    weak_min_fused: 0.42,
    strong_hit_min_ce: 0.6,
    strong_hit_min_lex: 0.15,
    weak_hit_min_vec: 0.75,
    min_lex_overlap: 0.05,
    top_k: 25,
    rrf_k_const: 60,
    query_fallback_top_k: 5,
    rerank_enabled: false,
  };
}

// ---------------------------------------------------------------------------
// Arg parsing — flags only, no prompts.
// ---------------------------------------------------------------------------
export function parseSetupArgs(args) {
  const out = { flags: {} };
  const valueFlags = ["--model", "--model-path", "--threads", "--instances", "--accel", "--graftd"];
  for (let i = 0; i < args.length; i++) {
    const a = args[i];
    if (a === "--detect-only") out.flags.detectOnly = true;
    else if (a === "--skip-daemon") out.flags.skipDaemon = true;
    else if (a === "--help" || a === "-h") out.flags.help = true;
    else if (valueFlags.includes(a)) {
      const val = args[++i];
      if (val === undefined) { out.error = `missing value for ${a}`; return out; }
      out.flags[a.slice(2).replace(/-([a-z])/g, (_, ch) => ch.toUpperCase())] = val;
    } else { out.error = `unknown argument: ${a}`; return out; }
  }
  return out;
}

// ---------------------------------------------------------------------------
// Model handling
// ---------------------------------------------------------------------------
export function validateModelPath(p) {
  if (!existsSync(p)) return { ok: false, reason: "file not found" };
  if (!p.endsWith(".gguf")) return { ok: false, reason: "not a .gguf file" };
  const size = statSync(p).size;
  if (size < 10 * 1024 * 1024) return { ok: false, reason: `file too small (${size} bytes, min 10MB)` };
  return { ok: true };
}

// Download via curl with size verification + atomic rename. Idempotent.
function downloadModel(entry) {
  const dir = modelsDir();
  mkdirSync(dir, { recursive: true });
  const target = join(dir, `${entry.id}.gguf`);
  if (existsSync(target)) {
    const size = statSync(target).size;
    if (Math.abs(size - entry.bytes) <= 1024 * 1024) {
      console.log(`model: ${entry.id} already present (${size} bytes) — skipping download`);
      return target;
    }
    console.log(`model: ${entry.id} present but size mismatch (${size} vs ${entry.bytes}) — re-downloading`);
  }
  const tmp = `${target}.tmp`;
  console.log(`model: downloading ${entry.id} (~${Math.round(entry.bytes / 1024 / 1024)}MB) → ${target}`);
  const r = sh("curl", ["-fsSL", "--retry", "3", "-o", tmp, entry.url]);
  if (!r.ok) {
    console.error(`download failed: ${r.err || "curl error"}`);
    try { unlinkSync(tmp); } catch { /* best effort */ }
    return null;
  }
  const size = statSync(tmp).size;
  if (Math.abs(size - entry.bytes) > 1024 * 1024) {
    console.error(`downloaded size ${size} ≠ catalog ${entry.bytes} — refusing`);
    return null;
  }
  renameSync(tmp, target);
  return target;
}

// ---------------------------------------------------------------------------
// Daemon install (macOS launchd; Linux prints a systemd pointer)
// ---------------------------------------------------------------------------
function renderPlist(graftdPath, configPath, logPath) {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
\t<key>Label</key>
\t<string>com.graft.daemon</string>
\t<key>ProgramArguments</key>
\t<array>
\t\t<string>${graftdPath}</string>
\t\t<string>--config</string>
\t\t<string>${configPath}</string>
\t</array>
\t<key>RunAtLoad</key>
\t<true/>
\t<key>KeepAlive</key>
\t<true/>
\t<key>StandardOutPath</key>
\t<string>${logPath}</string>
\t<key>StandardErrorPath</key>
\t<string>${logPath}</string>
</dict>
</plist>
`;
}

async function installDaemon(graftdPath, configPath) {
  if (process.platform !== "darwin") {
    console.log(`daemon: linux — run a systemd unit (or tmux) with: ${graftdPath} --config ${configPath}`);
    return true;
  }
  const uid = sh("id", ["-u"]).out;
  const label = "com.graft.daemon";
  const plist = plistPath();
  mkdirSync(dirname(plist), { recursive: true });
  writeFileSync(plist, renderPlist(graftdPath, configPath, join(os.homedir(), ".graft", "graftd.log")));
  console.log(`daemon: wrote ${plist}`);
  // bootout is asynchronous — wait until the service is actually gone, then
  // bootstrap. Retry bootstrap a few times: launchctl races are real (error 5).
  sh("launchctl", ["bootout", `gui/${uid}/${label}`]);
  for (let i = 0; i < 10; i++) {
    const s = sh("launchctl", ["print", `gui/${uid}/${label}`]);
    if (!s.ok) break; // "Could not find service" → unloaded
    await new Promise((r) => setTimeout(r, 500));
  }
  let b = { ok: false, err: "" };
  for (let i = 0; i < 3 && !b.ok; i++) {
    if (i > 0) await new Promise((r) => setTimeout(r, 1000));
    b = sh("launchctl", ["bootstrap", `gui/${uid}`, plist]);
  }
  if (!b.ok) {
    console.error(`daemon: bootstrap failed: ${b.err || b.out}`);
    return false;
  }
  const p = sh("launchctl", ["print", `gui/${uid}/${label}`]);
  if (p.ok && /state = running/i.test(p.out)) {
    console.log("daemon: running (launchd KeepAlive)");
    return true;
  }
  console.log("daemon: bootstrapped but state not confirmed — check ~/.graft/graftd.log");
  return true;
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------
export async function runSetup(args) {
  const parsed = parseSetupArgs(args);
  if (parsed.error) { console.error(`setup: ${parsed.error}`); return 1; }
  const f = parsed.flags;
  if (f.help) {
    console.log(`usage: heimdall setup [--model <catalog-id>] [--model-path /file.gguf]
                [--threads N] [--instances N] [--accel auto|metal|cuda|cpu]
                [--graftd /path/to/graftd] [--skip-daemon] [--detect-only]

Detects hardware, renders ~/.graft/config.yaml, optionally downloads the
embedding model, installs/repairs the launchd daemon. Verify with 'heimdall doctor'.`);
    return 0;
  }

  const hw = detectHardware();
  console.log(`hardware: ${hw.platform}, ${hw.cores} cores, accel=${hw.accel}, instances=${hw.instances}`);

  if (f.detectOnly) {
    console.log("detect-only: no files written");
    return 0;
  }

  // --- model resolution ---
  let modelPath = null;
  if (f.modelPath) {
    const v = validateModelPath(f.modelPath);
    if (!v.ok) { console.error(`--model-path invalid: ${f.modelPath} (${v.reason})`); return 1; }
    modelPath = f.modelPath;
  } else {
    const id = f.model || "bge-m3";
    const entry = CATALOG.find((m) => m.id === id);
    if (!entry) {
      console.error(`--model ${id} not in catalog: ${CATALOG.map((m) => m.id).join(", ")}`);
      return 1;
    }
    // Prefer an existing copy before downloading: vendored default, then ~/.graft/models.
    const vendorCopy = join(ROOT, "vendor", "graft", "models", `${entry.id}.gguf`);
    const homeCopy = join(modelsDir(), `${entry.id}.gguf`);
    if (existsSync(vendorCopy)) {
      modelPath = vendorCopy;
      console.log(`model: using vendored ${entry.id} at ${vendorCopy}`);
    } else if (existsSync(homeCopy)) {
      modelPath = homeCopy;
      console.log(`model: using existing ${entry.id} at ${homeCopy}`);
    } else {
      modelPath = downloadModel(entry);
      if (!modelPath) return 1;
    }
  }

  // --- choices from flags > detection ---
  const choices = defaultChoices(hw, modelPath);
  if (f.threads) choices.threads = parseInt(f.threads, 10) || choices.threads;
  if (f.instances) choices.instances = parseInt(f.instances, 10) || choices.instances;
  if (f.accel && f.accel !== "auto") {
    if (!["metal", "cuda", "cpu"].includes(f.accel)) {
      console.error(`--accel must be auto|metal|cuda|cpu (got ${f.accel})`);
      return 1;
    }
    choices.hardware_accel = f.accel === "metal" || f.accel === "cuda";
  }

  // --- config write with backup ---
  const cfgPath = graftConfigPath();
  if (existsSync(cfgPath)) {
    const bak = `${cfgPath}.bak-${Date.now()}`;
    copyFileSync(cfgPath, bak);
    console.log(`config: existing config backed up → ${bak}`);
  }
  mkdirSync(dirname(cfgPath), { recursive: true });
  writeFileSync(cfgPath, renderConfig(hw, choices));
  console.log(`config: wrote ${cfgPath} (model=${modelPath}, threads=${choices.threads}, instances=${choices.instances}, accel=${choices.hardware_accel ? hw.accel : "cpu"})`);

  if (f.modelPath || f.model) {
    console.log("warning: if a previous model was in use, existing embeddings are invalid — re-embed or rebuild affected profiles (see docs/setup.md)");
  }

  // --- daemon ---
  if (f.skipDaemon) {
    console.log(`daemon: skipped (--skip-daemon). Start manually: ${localBinGraftd()} --config ${cfgPath}`);
    return 0;
  }

  // graftd binary: --graftd path, else freshly built vendored binary, else existing install.
  let graftdSrc = f.graftd || null;
  const buildDir = join(ROOT, "vendor", "graft", "build", "graftd");
  const dest = localBinGraftd();
  if (!graftdSrc && existsSync(buildDir)) graftdSrc = buildDir;
  if (!graftdSrc && existsSync(dest)) graftdSrc = dest;
  if (!graftdSrc) {
    console.error(`daemon: no graftd found — pass --graftd /path/to/graftd or build: cmake -S ${join(ROOT, "vendor", "graft")} -B ${join(ROOT, "vendor", "graft", "build")} && cmake --build ${join(ROOT, "vendor", "graft", "build")}`);
    return 1;
  }
  mkdirSync(dirname(dest), { recursive: true });
  if (graftdSrc !== dest) {
    copyFileSync(graftdSrc, dest);
    chmodSync(dest, 0o755);
    console.log(`daemon: installed ${graftdSrc} → ${dest}`);
  }
  const okDaemon = await installDaemon(dest, cfgPath);
  console.log(okDaemon ? "done: run 'heimdall doctor' to verify" : "done with errors: see messages above");
  return okDaemon ? 0 : 1;
}
